// ============= HELPER FUNCTIONS =============
// =============================================

// Get products by category
export const getProductsByCategory = (category) => {
  return products.filter((product) => product.category === category);
};

// Get products by subCategory
export const getProductsBySubCategory = (subCategory) => {
  return products.filter((product) => product.subCategory === subCategory);
};

// Get best sellers
export const getBestSellers = () => {
  return products.filter((product) => product.bestSeller === true);
};

// Get products with videos
export const getProductsWithVideos = () => {
  return products.filter((product) => product.video && product.video !== "");
};

// Get products with catalogs
export const getProductsWithCatalogs = () => {
  return products.filter(
    (product) => product.catalog && product.catalog !== undefined,
  );
};

// Get natural products (Skincare or Hair Care)
export const getNaturalProducts = () => {
  return products.filter(
    (product) =>
      product.category === "Skincare" || product.category === "Hair Care",
  );
};

// Get products by skin type
export const getProductsBySkinType = (skinType) => {
  return products.filter(
    (product) => product.skinType && product.skinType.includes(skinType),
  );
};

// Get products by hair type
export const getProductsByHairType = (hairType) => {
  return products.filter(
    (product) => product.hairType && product.hairType.includes(hairType),
  );
};

// Get products by tag
export const getProductsByTag = (tag) => {
  return products.filter(
    (product) => product.tags && product.tags.includes(tag),
  );
};

// Get products by price range
export const getProductsByPriceRange = (min, max) => {
  return products.filter(
    (product) => product.price >= min && product.price <= max,
  );
};

// Get products with best rating
export const getTopRatedProducts = (limit = 4) => {
  return [...products]
    .sort((a, b) => (b.rating || 0) - (a.rating || 0))
    .slice(0, limit);
};

// Search products with enhanced SEO
export const searchProducts = (query) => {
  const lowercaseQuery = query.toLowerCase();
  return products.filter((product) => {
    const nameMatch = product.name.toLowerCase().includes(lowercaseQuery);
    const descMatch = product.description
      .toLowerCase()
      .includes(lowercaseQuery);
    const shortDescMatch =
      product.shortDescription?.toLowerCase().includes(lowercaseQuery) || false;
    const categoryMatch = product.category
      .toLowerCase()
      .includes(lowercaseQuery);
    const subCategoryMatch =
      product.subCategory?.toLowerCase().includes(lowercaseQuery) || false;
    const itemNoMatch =
      product.itemNo?.toLowerCase().includes(lowercaseQuery) || false;
    const typeMatch =
      product.type?.toLowerCase().includes(lowercaseQuery) || false;
    const tagMatch =
      product.tags?.some((tag) => tag.toLowerCase().includes(lowercaseQuery)) ||
      false;
    const benefitMatch =
      product.benefits?.some((benefit) =>
        benefit.toLowerCase().includes(lowercaseQuery),
      ) || false;
    const ingredientMatch =
      product.ingredients?.toLowerCase().includes(lowercaseQuery) || false;
    const skinTypeMatch =
      product.skinType?.some((type) =>
        type.toLowerCase().includes(lowercaseQuery),
      ) || false;

    return (
      nameMatch ||
      descMatch ||
      shortDescMatch ||
      categoryMatch ||
      subCategoryMatch ||
      itemNoMatch ||
      typeMatch ||
      tagMatch ||
      benefitMatch ||
      ingredientMatch ||
      skinTypeMatch
    );
  });
};

// Get product by ID
export const getProductById = (id) => {
  return products.find((product) => product.id === parseInt(id));
};

// Get related products
export const getRelatedProducts = (product, limit = 4) => {
  return products
    .filter((p) => p.id !== product.id && p.category === product.category)
    .slice(0, limit);
};

// Get product count by category
export const getProductCountByCategory = () => {
  const counts = {};
  products.forEach((product) => {
    counts[product.category] = (counts[product.category] || 0) + 1;
  });
  return counts;
};

// Get all unique tags
export const getAllTags = () => {
  const tags = new Set();
  products.forEach((product) => {
    if (product.tags) {
      product.tags.forEach((tag) => tags.add(tag));
    }
  });
  return Array.from(tags);
};

// Get all unique skin types
export const getAllSkinTypes = () => {
  const types = new Set();
  products.forEach((product) => {
    if (product.skinType) {
      product.skinType.forEach((type) => types.add(type));
    }
  });
  return Array.from(types);
};

// Get all unique hair types
export const getAllHairTypes = () => {
  const types = new Set();
  products.forEach((product) => {
    if (product.hairType) {
      product.hairType.forEach((type) => types.add(type));
    }
  });
  return Array.from(types);
};
